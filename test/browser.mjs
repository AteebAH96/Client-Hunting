import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright-core';
import { LeadStore } from '../lib/store.mjs';
import { createApp } from '../server.mjs';
import { updateLead } from '../lib/leads.mjs';
import { dateToday, addDays, ROOT } from '../lib/config.mjs';

for (const name of ['GOOGLE_PLACES_API_KEY', 'YOUTUBE_API_KEY', 'GEMINI_API_KEY']) process.env[name] = '';

const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'client-hunter-browser-'));
const store = new LeadStore(directory);
await store.initialize();
const outputDirectory = path.join(ROOT, '.qa');
await fs.mkdir(outputDirectory, { recursive: true });
const paths = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/google-chrome', '/usr/bin/chromium'].filter(Boolean);
let executablePath;
for (const candidate of paths) { try { await fs.access(candidate); executablePath = candidate; break; } catch {} }
if (!executablePath) throw new Error('Set CHROME_PATH to your installed Chrome or Edge executable to run browser tests.');
const server = createApp({ store }).listen(0, '127.0.0.1');
await new Promise((resolve) => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath, headless: true, args: ['--disable-gpu'], env: { ...process.env, TEMP: outputDirectory, TMP: outputDirectory } });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1120 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(() => document.getElementById('visible-count').textContent === '0 of 0 leads');
  await page.screenshot({ path: path.join(outputDirectory, 'desktop-empty.png'), fullPage: true });
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.click('#add-open');
  await page.fill('[name=name]', 'Browser QA channel');
  await page.selectOption('[name=type]', 'video');
  await page.fill('[name=source]', 'Browser test');
  await page.fill('[name=link]', 'https://youtube.com/channel/browser-fixture');
  await page.click('#add-submit');
  await page.waitForSelector('#detail-dialog[open]');
  assert.equal(await page.locator('#open-whatsapp').getAttribute('aria-disabled'), 'true');
  assert.equal(await page.locator('#no-phone').isVisible(), true);
  assert.match(await page.locator('#about-link').getAttribute('href'), /\/about$/);
  const message = 'Salam, "Channel"!\nAik free sample edit bhejoon?';
  await page.fill('#detail-message', message);
  await page.fill('#detail-notes', 'A note, with "quotes".\nAnd a second line.');
  await page.selectOption('#detail-status', 'sent');
  await page.waitForFunction(() => document.getElementById('save-state').textContent === 'All changes saved');
  const lead = (await store.read())[0];
  assert.equal(lead.message, message);
  assert.equal(lead.sent_date, dateToday());
  assert.equal(lead.followup_date, addDays(dateToday(), 3));
  await page.click('#copy-message');
  assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n'), message);
  await page.click('#detail-close');
  await page.reload();
  await page.waitForSelector('.lead-row');
  assert.equal(await page.locator('#count-sent').textContent(), '1');
  await page.click('.lead-row');
  assert.equal(await page.inputValue('#detail-message'), message);
  assert.equal(await page.inputValue('#detail-notes'), 'A note, with "quotes".\nAnd a second line.');
  await page.selectOption('#detail-status', 'replied');
  await page.waitForFunction(() => document.getElementById('save-state').textContent === 'All changes saved');
  assert.equal(await page.inputValue('#detail-followup'), '');
  await page.click('#draft-button');
  await page.waitForSelector('#detail-error:not([hidden])');
  assert.match(await page.locator('#detail-error').textContent(), /Missing GEMINI_API_KEY|no fetched channel facts/);
  assert.equal(await page.inputValue('#detail-message'), message);
  await page.click('#detail-close');
  await store.update(lead.id, (current) => updateLead(current, { status: 'sent', followup_date: '2020-01-01' }));
  // Set overdue after the sent transition, which deliberately assigns +3 days.
  await store.update(lead.id, (current) => updateLead(current, { followup_date: '2020-01-01' }));
  await page.click('#refresh-button');
  await page.waitForSelector('.followup-item .overdue');
  await page.screenshot({ path: path.join(outputDirectory, 'desktop-followup.png'), fullPage: true });
  await page.fill('#name-filter', 'No such lead');
  assert.equal(await page.locator('.lead-row').count(), 0);
  await page.fill('#name-filter', '');
  await page.selectOption('#type-filter', 'web');
  assert.equal(await page.locator('.lead-row').count(), 0);
  await page.selectOption('#type-filter', '');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.lead-row').evaluate((node) => getComputedStyle(node).display), 'grid');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(outputDirectory, 'phone-pipeline.png'), fullPage: true });
  await page.click('.lead-row');
  const panelBounds = await page.locator('#detail-dialog').boundingBox();
  assert.equal(Math.round(panelBounds.width), 390);
  assert.equal(Math.round(panelBounds.height), 844);
  assert.equal(Math.round(panelBounds.y), 0);
  assert.equal(await page.locator('#detail-dialog').evaluate((node) => node.scrollWidth <= node.clientWidth), true);
  await page.screenshot({ path: path.join(outputDirectory, 'phone-details.png') });
  await page.click('#delete-lead');
  await page.click('#delete-cancel');
  assert.equal((await store.read()).length, 1);
  await page.click('#delete-lead');
  await page.click('#delete-confirm');
  await page.waitForSelector('#detail-dialog', { state: 'hidden' });
  assert.equal((await store.read()).length, 0);
  const backups = await fs.readdir(store.backupDirectory);
  assert.ok((await Promise.all(backups.map((name) => fs.readFile(path.join(store.backupDirectory, name), 'utf8')))).some((csv) => csv.includes('Browser QA channel')));
  await page.reload();
  await page.waitForFunction(() => document.getElementById('visible-count').textContent === '0 of 0 leads');
  await page.click('[data-mode=video]');
  assert.match(await page.locator('#search-estimate').textContent(), /111 quota units/);
  await page.fill('#search-query', 'fixture niche');
  await page.click('#run-search');
  await page.waitForFunction(() => document.getElementById('job-label').textContent === 'SEARCH COULD NOT START');
  assert.match(await page.locator('#search-output').textContent(), /Missing YOUTUBE_API_KEY/);
  assert.deepEqual(errors, []);
  process.stdout.write('Browser checks passed: empty CSV, quoted multiline autosave, clipboard, no-phone lead, sent/replied dates, reload persistence, filters, overdue strip, delete confirmation and backup, missing-key errors, and 390px layout.\nScreenshots: .qa/desktop-empty.png, .qa/desktop-followup.png, .qa/phone-pipeline.png, .qa/phone-details.png\n');
} finally {
  await browser?.close();
  await new Promise((resolve) => server.close(resolve));
  await fs.rm(directory, { recursive: true, force: true });
}
